# Assigning values to three variables representing balls
ball_1 = 20  # Value of the first ball
ball_2 = -3   # Value of the second ball
ball_3 = 5   # Value of the third ball

# Calculating the total sum of the values of all balls
total_sum = ball_1 + ball_2 + ball_3  # Summing the values of ball_1, ball_2, and ball_3

# Printing the total sum to the console
print(total_sum)  # Output: 22